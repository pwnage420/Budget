def _write_dashboard(wb: Workbook, payload: ExportPayload) -> None:
    ws = wb.create_sheet("Dashboard")
    rows = [
        ("Generated", pd.Timestamp.utcnow().strftime("%Y-%m-%d %H:%M UTC")),
        ("Years of history", len(payload.history["year"].unique())),
        ("Horizon (weeks)", len(payload.forecast)),
        ("Blend strategy", payload.blend_strategy),
        ("Blend backtest RMSE", round(payload.blend_backtest_rmse, 3)),
    ]
    if payload.blend_weights:
        rows.append(("Weights", ", ".join(f"{k}: {v:.2f}" for k, v in payload.blend_weights.items())))
    if not payload.forecast.empty:
        rows.append(("Mean P50 ($/kg)", round(float(payload.forecast["mean"].mean()), 2)))
        rows.append(("Min P50 ($/kg)", round(float(payload.forecast["mean"].min()), 2)))
        rows.append(("Max P50 ($/kg)", round(float(payload.forecast["mean"].max()), 2)))
    df = pd.DataFrame(rows, columns=["KPI", "Value"])
    _write_dataframe(ws, df)


def _write_budget(wb: Workbook, payload: ExportPayload) -> None:
    ws = wb.create_sheet("Budget 2026")
    fc = payload.forecast.copy()
    if "date" in fc.columns:
        fc["Year"] = pd.to_datetime(fc["date"]).dt.isocalendar().year.astype(int)
        fc["Week"] = pd.to_datetime(fc["date"]).dt.isocalendar().week.astype(int)
    fc = fc.rename(columns={"mean": "P50", "p20": "P20", "p30": "P30",
                            "p70": "P70", "p80": "P80", "date": "Week Start"})
    cols = ["Year", "Week", "Week Start", "P20", "P30", "P50", "P70", "P80"]
    fc = fc[[c for c in cols if c in fc.columns]]
    for c in ("P20", "P30", "P50", "P70", "P80"):
        if c in fc.columns:
            fc[c] = fc[c].round(2)
    _write_dataframe(ws, fc)


def _write_fy_tracking(wb: Workbook, payload: ExportPayload) -> None:
    ws = wb.create_sheet("FY Tracking")
    fc = payload.forecast.copy()
    fc["Year"] = pd.to_datetime(fc["date"]).dt.isocalendar().year.astype(int)
    fc["Week"] = pd.to_datetime(fc["date"]).dt.isocalendar().week.astype(int)
    fc = fc.rename(columns={"date": "Week Start", "mean": "P50",
                            "p20": "P20", "p80": "P80"})
    cols = ["Year", "Week", "Week Start", "P20", "P50", "P80"]
    fc = fc[[c for c in cols if c in fc.columns]]
    fc["Actual"] = pd.NA
    fc["Variance ($)"] = pd.NA
    fc["Variance (%)"] = pd.NA
    fc["Position"] = pd.NA
    if payload.actuals is not None and not payload.actuals.empty:
        a = payload.actuals.copy()
        a["Year"] = pd.to_datetime(a["date"]).dt.isocalendar().year.astype(int)
        a["Week"] = pd.to_datetime(a["date"]).dt.isocalendar().week.astype(int)
        merged = fc.merge(a[["Year", "Week", "actual_price"]], on=["Year", "Week"], how="left")
        merged["Actual"] = merged["actual_price"]
        merged["Variance ($)"] = (merged["Actual"] - merged["P50"]).round(2)
        merged["Variance (%)"] = ((merged["Actual"] - merged["P50"]) / merged["P50"] * 100).round(1)
        def _pos(r):
            a = r["Actual"]
            if pd.isna(a):
                return ""
            if a < r["P20"]:
                return "Below"
            if a > r["P80"]:
                return "Above"
            return "Within"
        merged["Position"] = merged.apply(_pos, axis=1)
        fc = merged.drop(columns=["actual_price"])
    for c in ("P20", "P50", "P80"):
        if c in fc.columns:
            fc[c] = fc[c].round(2)
    _write_dataframe(ws, fc)


def _write_source_data(wb: Workbook, payload: ExportPayload) -> None:
    ws = wb.create_sheet("Source Data")
    df = payload.history.copy()
    df["date"] = pd.to_datetime(df["date"]).dt.date
    df = df.rename(columns={"date": "Week Start", "year": "Year",
                            "week": "Week", "price": "Price ($/kg)"})
    df["Price ($/kg)"] = df["Price ($/kg)"].round(2)
    _write_dataframe(ws, df)


def _write_model_comparison(wb: Workbook, payload: ExportPayload) -> None:
    ws = wb.create_sheet("Model Comparison")
    df = payload.metrics.copy()
    for c in ("rmse", "mae", "mape", "smape", "mase", "bias", "coverage_p20_p80",
              "fit_seconds"):
        if c in df.columns:
            df[c] = df[c].astype(float).round(4)
    _write_dataframe(ws, df)


def _write_methodology(wb: Workbook, payload: ExportPayload) -> None:
    ws = wb.create_sheet("Methodology")
    text = [
        "How this forecast was produced",
        "",
        "1. The app loaded weekly retail tomato prices ($/kg) from your source file.",
        "2. It fitted a panel of forecasting models — statistical baselines (Naive,",
        "   Seasonal+Trend, Holt-Winters, SARIMA) and machine-learning models",
        "   (Random Forest, XGBoost, LightGBM) — and optionally Prophet / N-BEATS /",
        "   TFT / Bayesian Structural Time Series when the Advanced toggle is on.",
        "3. Each model was backtested using walk-forward (expanding-window) cross-",
        "   validation on the most recent holdout year(s). They were ranked by",
        "   out-of-sample RMSE.",
        "4. The top 3 models were blended by inverse-RMSE weighting; if the blend",
        "   did not beat the best single model on backtest, the best single model",
        "   was emitted instead (spec guardrail).",
        "5. Probability bands (P20, P30, P70, P80) come from the residual standard",
        "   deviation pooled across folds + nearby horizon steps, then calibrated so",
        "   the P20–P80 band historically covers about 60% of holdout actuals.",
        "",
        f"Blend strategy used:    {payload.blend_strategy}",
        f"Blend backtest RMSE:    {payload.blend_backtest_rmse:.3f} ($/kg)",
        f"Model weights:          {payload.blend_weights}",
        "",
        "Full methodology and citations: see the app README.",
        "",
        payload.methodology_notes,
    ]
    for i, line in enumerate(text, start=1):
        c = ws.cell(row=i, column=1, value=_sanitize(line))
        c.font = _BODY_FONT
    ws.column_dimensions["A"].width = 100


def _write_backtest(wb: Workbook, payload: ExportPayload) -> None:
    ws = wb.create_sheet("Backtest")
    df = payload.metrics.copy()
    _write_dataframe(ws, df)
