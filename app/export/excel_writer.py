"""Excel export — nine-sheet workbook matching the spec's acceptance criterion 5.

Sheets, in order: README, Glossary, Dashboard, Budget 2026, FY Tracking, Source Data,
Model Comparison, Methodology, Backtest.

Security: every user-supplied string passes through `_sanitize` which prefixes a
single quote to defuse Excel formula injection (=, +, -, @, \t, \r).
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

INJECTION_TRIGGERS = ("=", "+", "-", "@", "\t", "\r")


def _sanitize(val):
    """Defuse CSV / Excel formula injection on user-supplied strings.

    Also coerces pandas/numpy missing values to None, which openpyxl handles natively.
    """
    if isinstance(val, str):
        if val and val[0] in INJECTION_TRIGGERS:
            return "'" + val
        return val
    # Catch pd.NA, numpy.nan, NaT, None — these all blow up openpyxl
    try:
        if val is None:
            return None
        if pd.isna(val):
            return None
    except (TypeError, ValueError):
        pass
    return val


@dataclass
class ExportPayload:
    history: pd.DataFrame                    # date, year, week, price
    forecast: pd.DataFrame                   # date, mean, p20, p30, p70, p80
    metrics: pd.DataFrame                    # per-model backtest summary
    blend_weights: dict[str, float]
    blend_strategy: str
    blend_backtest_rmse: float
    actuals: pd.DataFrame | None = None       # date, actual_price
    methodology_notes: str = ""


def export_workbook(payload: ExportPayload, path: str | Path) -> Path:
    path = Path(path)
    wb = Workbook()
    wb.remove(wb.active)

    _write_readme(wb)
    _write_glossary(wb)
    _write_dashboard(wb, payload)
    _write_budget(wb, payload)
    _write_fy_tracking(wb, payload)
    _write_source_data(wb, payload)
    _write_model_comparison(wb, payload)
    _write_methodology(wb, payload)
    _write_backtest(wb, payload)

    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


# ----- sheet writers ------------------------------------------------------------------

_HEADER_FILL = PatternFill(start_color="1F2937", end_color="1F2937", fill_type="solid")
_HEADER_FONT = Font(name="Inter", size=11, bold=True, color="F9FAFB")
_BODY_FONT = Font(name="Inter", size=10)
_THIN = Side(border_style="thin", color="E5E7EB")
_BORDER = Border(left=_THIN, right=_THIN, top=_THIN, bottom=_THIN)


def _style_header(cell):
    cell.fill = _HEADER_FILL
    cell.font = _HEADER_FONT
    cell.alignment = Alignment(horizontal="left", vertical="center")
    cell.border = _BORDER


def _style_body(cell):
    cell.font = _BODY_FONT
    cell.border = _BORDER


def _write_dataframe(ws, df: pd.DataFrame, start_row: int = 1) -> int:
    cols = list(df.columns)
    for j, col in enumerate(cols, start=1):
        c = ws.cell(row=start_row, column=j, value=_sanitize(str(col)))
        _style_header(c)
    for i, (_, row) in enumerate(df.iterrows(), start=start_row + 1):
        for j, col in enumerate(cols, start=1):
            val = row[col]
            if hasattr(val, "to_pydatetime"):
                val = val.to_pydatetime()
            c = ws.cell(row=i, column=j, value=_sanitize(val))
            _style_body(c)
    for j, col in enumerate(cols, start=1):
        ws.column_dimensions[get_column_letter(j)].width = max(12, min(28, len(str(col)) + 4))
    return start_row + 1 + len(df)


def _write_readme(wb: Workbook) -> None:
    ws = wb.create_sheet("README")
    lines = [
        "Goodness Grown — Tomato Price Forecaster",
        "",
        "This workbook is an export from the desktop forecasting app that replaces the",
        "v4 Excel budget model. The sheets are ordered for board reporting:",
        "",
        "  Dashboard         — KPI summary",
        "  Budget 2026       — recommended weekly budget ($/kg, P50 + P20/P80 bands)",
        "  FY Tracking       — week-by-week actual vs forecast, with variance",
        "  Source Data       — raw weekly prices used for fitting",
        "  Model Comparison  — backtest table, every model ranked by out-of-sample RMSE",
        "  Methodology       — short summary of how the forecast was produced",
        "  Backtest          — per-fold per-model error metrics for audit",
        "  Glossary          — every abbreviation used in the workbook",
        "",
        "All values are in AUD per kilogram. AU financial year runs July to June.",
        "Generated by Goodness Grown Tomato Price Forecaster — see the app README.",
    ]
    for i, line in enumerate(lines, start=1):
        c = ws.cell(row=i, column=1, value=_sanitize(line))
        c.font = _BODY_FONT
    ws.column_dimensions["A"].width = 100


